// Renders the tokens as CSS: `:root` variables (light + dark) and a Tailwind v4 `@theme inline` block
// that maps utility names (bg-primary, text-muted, rounded-lg, …) onto those variables.
import { colors, fontFamilies, fontSizes, radii, type ColorRole } from './tokens.ts';

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const colorVars = (scheme: Record<ColorRole, string>, indent: string) =>
  Object.entries(scheme)
    .map(([role, value]) => `${indent}--am-${kebab(role)}: ${value};`)
    .join('\n');

export function renderCss(): string {
  const roles = Object.keys(colors.light) as ColorRole[];
  const themeColors = roles
    .map((role) => `  --color-${kebab(role)}: var(--am-${kebab(role)});`)
    .join('\n');
  const themeRadii = Object.entries(radii)
    .filter(([name]) => name !== 'full')
    .map(([name, px]) => `  --radius-${name}: ${px / 16}rem;`)
    .join('\n');
  const themeText = Object.entries(fontSizes)
    .map(
      ([name, [size, leading]]) =>
        `  --text-${name}: ${size / 16}rem;\n  --text-${name}--line-height: ${leading / 16}rem;`,
    )
    .join('\n');
  const fonts = (list: readonly string[]) =>
    list.map((f) => (f.includes('-') ? f : `"${f}"`)).join(', ');

  return `/* GENERATED by @ashan/tokens (pnpm tokens). Do not edit by hand. */
:root {
  color-scheme: light;
${colorVars(colors.light, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${colorVars(colors.dark, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${colorVars(colors.dark, '  ')}
}

@theme inline {
${themeColors}
  --font-sans: var(--font-inter), var(--font-mukta), ${fonts(fontFamilies.sans.slice(2))};
  --font-devanagari: var(--font-mukta), var(--font-inter), ${fonts(fontFamilies.devanagari.slice(2))};
${themeRadii}
${themeText}
}
`;
}
