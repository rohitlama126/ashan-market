// Generates supabase/seed.sql from catalog.json (+ local demo accounts).
// Run: pnpm db:seed:build   then   pnpm db:reset
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (rel) => fileURLToPath(new URL(rel, import.meta.url));
const data = JSON.parse(readFileSync(here('./catalog.json'), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a = []) => `array[${a.map(q).join(', ')}]::text[]`;
const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

const out = [];
out.push(`-- GENERATED by supabase/seed/build-seed.mjs from catalog.json. Do not edit by hand.
-- Local development data only: ${data._note}

insert into public.vendors (slug, name, is_house) values ('ashan-market', 'Ashan Market', true);
insert into public.stock_locations (vendor_id, name, kind)
  select id, 'Main warehouse', 'warehouse' from public.vendors where slug = 'ashan-market';
`);

out.push('insert into public.categories (slug, name_en, name_ne, sort) values');
out.push(
  data.categories.map((c, i) => `  (${q(c.slug)}, ${q(c.en)}, ${q(c.ne)}, ${i})`).join(',\n') +
    ';\n',
);

const brands = [...new Set(data.products.map((p) => p.brand))];
out.push('insert into public.brands (slug, name) values');
out.push(brands.map((b) => `  (${q(slugify(b))}, ${q(b)})`).join(',\n') + ';\n');

data.products.forEach((p, i) => {
  out.push(`-- ${p.en}
insert into public.products (vendor_id, brand_id, category_id, slug, name_en, name_ne, description_en, description_ne, tags, dietary, spice_level, status, featured_rank)
select v.id, b.id, c.id, ${q(p.slug)}, ${q(p.en)}, ${q(p.ne)}, ${q(p.desc_en)}, ${q(p.desc_ne)}, ${arr(p.tags)}, ${arr(p.dietary)}, ${p.spice ?? 'null'}, 'active', ${i + 1}
from public.vendors v, public.brands b, public.categories c
where v.slug = 'ashan-market' and b.slug = ${q(slugify(p.brand))} and c.slug = ${q(p.category)};

insert into public.product_compliance (product_id, country_of_origin, ingredients_en, allergens, may_contain, manufacturer_name, english_label_verified)
select id, ${q(p.origin)}, ${q(p.ingredients)}, ${arr(p.allergens)}, ${arr(p.may_contain)}, ${q(p.brand)}, false
from public.products where slug = ${q(p.slug)};
`);
  p.variants.forEach((v, j) => {
    const sku = `AM-${String(i + 1).padStart(3, '0')}-${j + 1}`;
    out.push(`insert into public.variants (product_id, sku, title_en, title_ne, price_cents, compare_at_cents, net_weight_g, shipping_class, sort)
select id, ${q(sku)}, ${q(v.en)}, ${q(v.ne)}, ${v.price}, ${v.compare ?? 'null'}, ${v.grams}, ${q(v.shipping ?? 'ambient')}, ${j}
from public.products where slug = ${q(p.slug)};
insert into public.inventory_levels (variant_id, location_id, on_hand)
select vr.id, l.id, ${v.stock} from public.variants vr, public.stock_locations l
where vr.sku = ${q(sku)} and l.name = 'Main warehouse';
`);
  });
});

// Demo shopper for local testing. Phone sign-in uses the fixed test code from config.toml,
// so no email is needed: (718) 555-0134, code 123456.
out.push(`-- Local demo customer: phone +1 (718) 555-0134, code 123456 (see supabase/config.toml).
do $$
declare uid uuid := '0d3c0de0-0000-4000-8000-00000000a5a1';
begin
  insert into auth.users (instance_id, id, aud, role, email, phone, phone_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change_token_new, email_change)
  values ('00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated', '', '17185550134', now(),
    '{"provider":"phone","providers":["phone"]}', '{"full_name":"Sita Gurung","locale":"en"}', now(), now(),
    '', '', '', '');
  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), uid, uid::text,
    jsonb_build_object('sub', uid::text, 'phone', '17185550134', 'phone_verified', true),
    'phone', now(), now(), now());
  update public.profiles set home_zip = '11372' where id = uid;
end $$;
`);

writeFileSync(here('../seed.sql'), out.join('\n'));
console.log(
  `seed.sql: ${data.categories.length} categories, ${brands.length} brands, ${data.products.length} products, ${data.products.reduce((n, p) => n + p.variants.length, 0)} variants, 1 demo customer`,
);
